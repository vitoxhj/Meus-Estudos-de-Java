package estudosJava.introducao.estruturasDeRepetição;

public class Acumuladores {
    public static void main(String[] args) {
        //Some todos os numeros do loop
        int soma = 0;
        for (int i = 0; i <= 1294; i++) {
            soma += i;
        }
        System.out.println("Soma: "+soma);
    }
    
}
